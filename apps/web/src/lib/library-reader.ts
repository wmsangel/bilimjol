export type ReaderKind = "poem" | "prose";

export interface ReaderWork {
  /** url-сегмент, латиница: "vorona-i-lisica" */
  slug: string;
  title: string; // «Ворона и Лисица»
  author: string; // «И. А. Крылов»
  year?: string; // «1807»
  kind: ReaderKind; // poem — сохраняем переносы строк; prose — абзацы
  /** Откуда взят текст (первоисточник, напр. Викитека). */
  sourceUrl: string;
  license: "public-domain";
  /** 1–2 предложения: о чём (для карточки и SEO-описания). */
  summary: { ru: string; ky: string };
  /**
   * Сам текст ДОСЛОВНО. Строки разделяются "\n", строфы/абзацы — "\n\n".
   * Для poem каждая строка выводится отдельно; для prose "\n\n" — граница абзаца.
   */
  body: string;
}

