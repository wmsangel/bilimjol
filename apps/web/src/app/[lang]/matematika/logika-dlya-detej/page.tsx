export async function generateMetadata({
  params,
}: {
  params: Promise<{ lang: string }>;
}): Promise<Metadata> {
  const { lang } = await params;
  if (!isLocale(lang)) return {};
  const ky = lang === "ky";
  return {
    title: ky
      ? "Логика тапшырмалары 5–6 жаштагы балдарга — акысыз | Bilimjol"
      : "Задания на логику для детей 5–6 лет — бесплатно | Bilimjol",
    description: ky
      ? "5–6 жаштагы балдарга логика тапшырмалары: ашыкчасын тап, катарды улант, көлөкө, салыштыруу. Үйдө кантип машыгуу керек жана акысыз логикалык оюндар катталуусуз."
      : "Задания на логику для детей 5–6 лет: найди лишнее, продолжи ряд, тень, сравнение. Как развивать логику дошкольника дома и бесплатные логические игры без регистрации.",
    alternates: localizedAlternates(lang, "/matematika/logika-dlya-detej"),
  };
}

