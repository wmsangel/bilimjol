// P1 — «разгон» сложности: лёгкие и средние задания в темы старших классов,
// где раньше было только сложное. Дают ребёнку победы на старте темы.
// Все бесплатные (расширяют и free-контент).

type Pair = [string, string];

function num(
  id: string, topic: string, grade: number, d: Difficulty, answer: number,
  ru: string, ky: string, eRu: string, eKy: string,
): Task {
  return { id, type: "number_input", subject: "math", topic, grade, difficulty: d,
    free: true, prompt: { ru, ky }, answer, explanation: { ru: eRu, ky: eKy } };
}
function multi(
  id: string, topic: string, grade: number, d: Difficulty,
  ru: string, ky: string, options: Pair[], correctIndexes: number[], eRu: string, eKy: string,
): Task {
  return { id, type: "multi_select", subject: "math", topic, grade, difficulty: d,
    free: true, prompt: { ru, ky }, options: options.map(([r, k]) => ({ ru: r, ky: k })),
    correctIndexes, explanation: { ru: eRu, ky: eKy } };
}

