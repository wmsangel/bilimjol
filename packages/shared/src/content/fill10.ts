type Pair = [string, string];
const L = (a: Pair[]) => a.map(([ru, ky]) => ({ ru, ky }));

function num(
  id: string, topic: string, grade: number, answer: number,
  ru: string, ky: string, eRu: string, eKy: string,
  difficulty: Difficulty = 2, star = false,
): Task {
  return {
    id, type: "number_input", subject: "reading", topic, grade, difficulty, free: true, star,
    prompt: { ru, ky }, answer, explanation: { ru: eRu, ky: eKy },
  };
}
function choice(
  id: string, topic: string, grade: number, correctIndex: number,
  ru: string, ky: string, options: Pair[], eRu: string, eKy: string,
  difficulty: Difficulty = 2, star = false,
): Task {
  return {
    id, type: "single_choice", subject: "reading", topic, grade, difficulty, free: true, star,
    prompt: { ru, ky }, options: L(options), correctIndex, explanation: { ru: eRu, ky: eKy },
  };
}

