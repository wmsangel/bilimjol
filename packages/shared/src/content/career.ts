/** Баллы по типам из массива ответов (0/1/2), параллельного careerQuestions. */
export function scoreCareer(answers: number[]): Record<CareerTypeId, number> {
  const s: Record<CareerTypeId, number> = { R: 0, I: 0, A: 0, S: 0, E: 0, C: 0 };
  answers.forEach((v, i) => {
    const q = careerQuestions[i];
    if (q) s[q.type] += v;
  });
  return s;
}

const ORDER: CareerTypeId[] = ["R", "I", "A", "S", "E", "C"];

/** Топ-N типов (по баллам; при равенстве — канонический порядок RIASEC). */
export function topCareerTypes(answers: number[], n = 3): CareerTypeId[] {
  const s = scoreCareer(answers);
  return [...ORDER].sort((a, b) => s[b] - s[a] || ORDER.indexOf(a) - ORDER.indexOf(b)).slice(0, n);
}

export function getCareerType(id: CareerTypeId): CareerType {
  return careerTypes.find((t) => t.id === id) ?? careerTypes[0];
}

