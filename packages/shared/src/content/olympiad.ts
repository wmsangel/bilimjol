const num = (
  id: string,
  grade: number,
  answer: number,
  ru: string,
  ky: string,
  eRu: string,
  eKy: string,
  free = true,
): Task => ({
  id,
  type: "number_input",
  subject: "olympiad",
  topic: `oly-${grade}`,
  grade,
  difficulty: 3,
  free,
  prompt: { ru, ky },
  answer,
  explanation: { ru: eRu, ky: eKy },
});

