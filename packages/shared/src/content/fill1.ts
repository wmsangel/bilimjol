// Наполнение тонких предметов (логика / окружающий мир / олимпиада) для классов
// 2–11 + разнообразие механик. Короткие фактические/логические задания.
// NB: кыргызский — аккуратный, но стоит вычитки носителем.

type Pair = [string, string];
const L = (a: Pair[]) => a.map(([ru, ky]) => ({ ru, ky }));

function choice(
  id: string, topic: string, subject: Task["subject"], grade: number,
  ru: string, ky: string, options: Pair[], correctIndex: number,
  eRu: string, eKy: string, difficulty: Difficulty = 2, star = false,
): Task {
  return { id, type: "single_choice", subject, topic, grade, difficulty, free: true, star,
    prompt: { ru, ky }, options: L(options), correctIndex, explanation: { ru: eRu, ky: eKy } };
}
function multi(
  id: string, topic: string, subject: Task["subject"], grade: number,
  ru: string, ky: string, options: Pair[], correctIndexes: number[],
  eRu: string, eKy: string, difficulty: Difficulty = 2,
): Task {
  return { id, type: "multi_select", subject, topic, grade, difficulty, free: true,
    prompt: { ru, ky }, options: L(options), correctIndexes, explanation: { ru: eRu, ky: eKy } };
}
function order(
  id: string, topic: string, subject: Task["subject"], grade: number,
  ru: string, ky: string, items: Pair[], eRu: string, eKy: string,
  difficulty: Difficulty = 2,
): Task {
  return { id, type: "ordering", subject, topic, grade, difficulty, free: true,
    prompt: { ru, ky }, items: L(items), explanation: { ru: eRu, ky: eKy } };
}

