import type { Task, Difficulty } from "./types";

// Разнообразие механик: «отметь все верные» (multi_select), «расставь по порядку»
// (ordering) и «соедини пары» (match_pairs) — подмешиваются в существующие темы,
// чтобы занятия не состояли только из выбора и ввода числа.
// Плюс здесь же тема «Мир вокруг» для подготовительного класса (grade 0).

type Pair = [string, string]; // [ru, ky]
const L = (arr: Pair[]) => arr.map(([ru, ky]) => ({ ru, ky }));

function multi(
  id: string, topic: string, subject: Task["subject"], grade: number,
  ru: string, ky: string, options: Pair[], correctIndexes: number[],
  eRu: string, eKy: string, free = true, difficulty: Difficulty = 2,
): Task {
  return { id, type: "multi_select", subject, topic, grade, difficulty, free,
    prompt: { ru, ky }, options: L(options), correctIndexes, explanation: { ru: eRu, ky: eKy } };
}
function order(
  id: string, topic: string, subject: Task["subject"], grade: number,
  ru: string, ky: string, items: Pair[], eRu: string, eKy: string,
  free = true, difficulty: Difficulty = 2,
): Task {
  return { id, type: "ordering", subject, topic, grade, difficulty, free,
    prompt: { ru, ky }, items: L(items), explanation: { ru: eRu, ky: eKy } };
}
function pairs(
  id: string, topic: string, subject: Task["subject"], grade: number,
  ru: string, ky: string, left: Pair[], right: Pair[], eRu: string, eKy: string,
  free = true, difficulty: Difficulty = 2,
): Task {
  return { id, type: "match_pairs", subject, topic, grade, difficulty, free,
    prompt: { ru, ky }, left: L(left), right: L(right), explanation: { ru: eRu, ky: eKy } };
}
function choice(
  id: string, topic: string, subject: Task["subject"], grade: number,
  ru: string, ky: string, options: Pair[], correctIndex: number,
  eRu: string, eKy: string, free = true, difficulty: Difficulty = 1, star = false,
): Task {
  return { id, type: "single_choice", subject, topic, grade, difficulty, free, star,
    prompt: { ru, ky }, options: L(options), correctIndex, explanation: { ru: eRu, ky: eKy } };
}

