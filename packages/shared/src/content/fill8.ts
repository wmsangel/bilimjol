type Pair = [string, string];
const L = (a: Pair[]) => a.map(([ru, ky]) => ({ ru, ky }));

function choice(
  id: string, topic: string, grade: number,
  ru: string, ky: string, options: Pair[], correctIndex: number,
  eRu: string, eKy: string, difficulty: Difficulty = 2, star = false,
): Task {
  return {
    id, type: "single_choice", subject: "logic", topic, grade, difficulty, free: true, star,
    prompt: { ru, ky }, options: L(options), correctIndex, explanation: { ru: eRu, ky: eKy },
  };
}
function num(
  id: string, topic: string, grade: number,
  ru: string, ky: string, answer: number, eRu: string, eKy: string,
  difficulty: Difficulty = 2, star = false,
): Task {
  return {
    id, type: "number_input", subject: "logic", topic, grade, difficulty, free: true, star,
    prompt: { ru, ky }, answer, explanation: { ru: eRu, ky: eKy },
  };
}

